import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const manifest = JSON.parse(
	fs.readFileSync(new URL('./image-manifest.json', import.meta.url), 'utf8')
);

const LQIP_MANIFEST_PATH = path.resolve(process.cwd(), 'src/lib/data/image-lqips.ts');
const SRCSET_MANIFEST_PATH = path.resolve(process.cwd(), 'src/lib/data/image-srcsets.ts');

// Width of the tiny blurred placeholder images used for gradual loading.
const LQIP_WIDTH = 48;

const FORCE = process.argv.includes('--force');

async function main() {
	let generated = 0;
	let skipped = 0;
	const lqipEntries = [];
	const srcsetEntries = [];

	for (const entry of manifest) {
		const sourcePath = path.resolve(process.cwd(), entry.src);
		if (!fs.existsSync(sourcePath)) {
			console.error(`Missing source image: ${entry.src}`);
			process.exitCode = 1;
			continue;
		}

		const { width: sourceWidth } = await sharp(sourcePath).metadata();
		const ext = path.extname(entry.src);
		const extRegex = new RegExp(`${ext.replace('.', '\\.')}$`);

		// Only record widths that were actually baked (never upscale).
		const bakedWidths = [];
		for (const width of entry.widths) {
			if (sourceWidth && width > sourceWidth) {
				console.log(`Skipping ${entry.src} @ ${width}w (source is ${sourceWidth}w)`);
				skipped++;
				continue;
			}
			bakedWidths.push(width);

			const outputPath = sourcePath.replace(extRegex, `-${width}w.avif`);

			if (
				!FORCE &&
				fs.existsSync(outputPath) &&
				fs.statSync(outputPath).mtimeMs > fs.statSync(sourcePath).mtimeMs
			) {
				skipped++;
				continue;
			}

			await sharp(sourcePath).resize({ width }).avif({ quality: 55, effort: 4 }).toFile(outputPath);
			generated++;
			console.log(`Generated ${path.relative(process.cwd(), outputPath)}`);
		}

		// Tiny blurred placeholder (LQIP) for gradual image loading.
		const lqipOutputPath = sourcePath.replace(extRegex, '-lqip.avif');

		if (
			!FORCE &&
			fs.existsSync(lqipOutputPath) &&
			fs.statSync(lqipOutputPath).mtimeMs > fs.statSync(sourcePath).mtimeMs
		) {
			skipped++;
		} else {
			await sharp(sourcePath)
				.resize({ width: LQIP_WIDTH })
				.blur(6)
				.avif({ quality: 45, effort: 3 })
				.toFile(lqipOutputPath);
			generated++;
			console.log(`Generated ${path.relative(process.cwd(), lqipOutputPath)}`);
		}

		const { width: lqipWidth, height: lqipHeight } = await sharp(lqipOutputPath).metadata();

		const sitePath = entry.src.replace(/^static/, '');
		const siteBase = sitePath.slice(0, -ext.length);
		lqipEntries.push({
			sitePath,
			lqipPath: siteBase + '-lqip.avif',
			width: lqipWidth,
			height: lqipHeight
		});
		srcsetEntries.push({
			siteBase,
			variants: bakedWidths
				.sort((a, b) => a - b)
				.map((width) => ({ url: `${siteBase}-${width}w.avif`, width }))
		});
	}

	// LQIP lookup for gradual image loading. Dedupe keys defensively in case
	// the manifest ever lists the same source twice.
	const lqipMap = new Map();
	for (const entry of lqipEntries) {
		lqipMap.set(entry.sitePath, entry);
	}
	const lqipLines = [...lqipMap.entries()]
		.map(
			([sitePath, { lqipPath, width, height }]) =>
				`\t'${sitePath}': { src: '${lqipPath}', width: ${width}, height: ${height} },`
		)
		.join('\n');

	fs.writeFileSync(
		LQIP_MANIFEST_PATH,
		[
			'// AUTO-GENERATED by scripts/generate-images.mjs — do not edit by hand.',
			'// Maps image site paths to their low-quality placeholders (LQIP) for',
			'// gradual image loading.',
			'',
			'export type ImageLqip = {',
			'\tsrc: string;',
			'\twidth: number;',
			'\theight: number;',
			'};',
			'',
			'export const imageLqips: Record<string, ImageLqip> = {',
			lqipLines,
			'};',
			''
		].join('\n')
	);

	// Multi-width AVIF variants lookup (used to build responsive srcsets).
	// Dedupe keys defensively in case the manifest ever lists a source twice.
	const srcsetMap = new Map();
	for (const entry of srcsetEntries) {
		const existing = srcsetMap.get(entry.siteBase) ?? [];
		const mergedVariants = new Map();
		for (const variant of [...existing, ...entry.variants]) {
			mergedVariants.set(variant.width, variant);
		}
		srcsetMap.set(
			entry.siteBase,
			[...mergedVariants.values()].sort((a, b) => a.width - b.width)
		);
	}
	const srcsetLines = [...srcsetMap.entries()]
		.map(([siteBase, variants]) => {
			const variantLines = variants
				.map(({ url, width }) => `\t\t{ url: '${url}', width: ${width} },`)
				.join('\n');
			return `\t'${siteBase}': [\n${variantLines}\n\t],`;
		})
		.join('\n');

	fs.writeFileSync(
		SRCSET_MANIFEST_PATH,
		[
			'// AUTO-GENERATED by scripts/generate-images.mjs — do not edit by hand.',
			'// Multi-width AVIF variants baked for each image source, keyed by the',
			"// source's site path without its extension.",
			'',
			'export type ImageVariant = {',
			'\turl: string;',
			'\twidth: number;',
			'};',
			'',
			'export const imageVariants: Record<string, ImageVariant[]> = {',
			srcsetLines,
			'};',
			'',
			'export function getImageVariants(sitePath: string): ImageVariant[] {',
			"\tconst ext = sitePath.slice(sitePath.lastIndexOf('.'));",
			'\treturn imageVariants[sitePath.slice(0, -ext.length)] ?? [];',
			'}',
			'',
			'// Sizes hint for the project grid cards (col-sm-12 / col-md-6 / col-lg-4).',
			"export const GRID_IMAGE_SIZES = '(min-width: 992px) 33vw, (min-width: 768px) 50vw, 100vw';",
			''
		].join('\n')
	);

	console.log(`Done: ${generated} generated, ${skipped} skipped.`);
}

main().catch((error) => {
	console.error(error);
	process.exit(1);
});
